-- The layout of the Postgres schema (migrations/postgres, after 031) on
-- Spanner's PostgreSQL interface (SPANNER.md; dialect.go, spanner.go).
-- The tables, columns and keys are Postgres's; what differs:
--
--   - integers are bigint throughout: Spanner has no smallint or integer.
--     Flags and codes are compared with 0 and 1, as on both dialects;
--   - the ids of revisions, ns_log, ns_config and archives are no
--     identities: Spanner's are bit-reversed, so they don't grow, and
--     those of a chain must grow along it (§3.5, D.8). The engine takes
--     them from id_blocks (spannerids.go), above the chain's head. The
--     other identities (namespaces, resources, authors, cdn_repurge) are
--     only keys, and BIT_REVERSED_POSITIVE spreads them over the key space;
--   - UNIQUE constraints are unique indexes; a nullable column's are
--     NULL_FILTERED (WHERE … IS NOT NULL), since Spanner's unique indexes
--     count NULLs as equal and Postgres's UNIQUE doesn't;
--   - the partial unique indexes one_first, one_ns_first and
--     one_config_genesis are on a generated column that holds the chain's
--     key on its first row alone and NULL elsewhere, null-filtered:
--     Spanner's partial indexes filter on IS NOT NULL only;
--   - no COLLATE "C": Spanner orders text by its UTF-8 bytes, which is
--     the order those indexes exist for (§7.4);
--   - ns_log.committed, the commit timestamp of the entry's transaction
--     (spanner.pending_commit_timestamp() on insert), replaces xid: the
--     tailer reads what committed after the last timestamp it saw
--     (tailer.go);
--   - no functions (rate_draw, rate_draws): Spanner has none, and the
--     rate buckets are kept in memory (ratebuckets.go);
--   - no foreign keys (REFERENCES): each would be a hidden index Spanner
--     writes with every row and a check at commit, on the write path a good
--     part of a group commit's inserts (SPANNER.md, the first bench run).
--     The engine keeps the references itself, as on every dialect; Postgres
--     and SQLite keep their constraints;
--   - id_blocks and leader_lease, for what Postgres sequences and
--     advisory locks did (spannerids.go, pglock.go).
--
-- DDL runs outside transactions (dbmigrate's Spanner runner), so every
-- statement is IF NOT EXISTS: a migration interrupted halfway is run again
-- from its start.

