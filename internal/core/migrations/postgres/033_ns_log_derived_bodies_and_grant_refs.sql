-- Derived ns_log columns and grant references by number (docs/capacity/
-- storage, CHANGELOG):
--
-- ns_log.body and ns_log.created of a head or tombstone entry are NULL when
-- the entry is exactly { kind, resource, target } of the revision its write
-- inserted (entrybody.go): the body is rebuilt from l.kind, the name of
-- l.res and the id of l.target_seq, byte for byte as hashed (§3.5), and
-- created is the revision's, written in the same transaction. Rows written
-- before keep their bodies: nothing is rewritten, and dropping NOT NULL
-- only changes the catalog.
--
-- grants.ref numbers each stored grant once (filling the rows there are,
-- which rewrites grants alone); ns_log.grant_ref and revisions.grant_ref
-- name a grant by it in place of the 20-byte grant_id, which rows written
-- before keep (reads take either). Adding the nullable columns only
-- changes the catalog.
ALTER TABLE ns_log ALTER COLUMN body DROP NOT NULL, ALTER COLUMN created DROP NOT NULL;
ALTER TABLE grants ADD COLUMN IF NOT EXISTS ref bigint GENERATED BY DEFAULT AS IDENTITY;
CREATE UNIQUE INDEX IF NOT EXISTS grants_ref ON grants (ref);
ALTER TABLE ns_log ADD COLUMN IF NOT EXISTS grant_ref bigint;
ALTER TABLE revisions ADD COLUMN IF NOT EXISTS grant_ref bigint;
-- The entries recording a grant by number, as ns_log_by_grant does by id
-- (grants.go, archive.go).
CREATE INDEX IF NOT EXISTS ns_log_by_grant_ref ON ns_log (grant_ref, ns, seq) WHERE grant_ref IS NOT NULL;
