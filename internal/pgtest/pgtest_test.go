package pgtest

import (
	"database/sql"
	"testing"
)

// A database goes back to the pool empty, its sequences restarted, its
// schema kept, any session a test left open ended; one whose schema a test
// changed is dropped instead.
func TestPool(t *testing.T) {
	if !Enabled() || Spanner() {
		t.Skip("Postgres only (" + Env + ")")
	}
	var first string
	var leftOpen *sql.DB
	t.Run("write", func(t *testing.T) {
		first = NewDB(t)
		db := Open(t, first)
		exec(t, db, `CREATE TABLE a (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text NOT NULL)`,
			`CREATE TABLE b (a bigint NOT NULL REFERENCES a)`,
			`INSERT INTO a (v) VALUES ('x'), ('y')`, `INSERT INTO b VALUES (2)`)
		leftOpen = db // never closed: emptying ends its session
	})
	defer leftOpen.Close()
	t.Run("reuse", func(t *testing.T) {
		if got := NewDB(t); got != first {
			t.Fatalf("got %s, want the pool's %s", got, first)
		}
		db := Open(t, first)
		defer db.Close()
		var n int
		if err := db.QueryRow(`SELECT (SELECT count(*) FROM a) + (SELECT count(*) FROM b)`).Scan(&n); err != nil || n != 0 {
			t.Fatalf("rows left: %d, %v", n, err)
		}
		var id int64
		if err := db.QueryRow(`INSERT INTO a (v) VALUES ('z') RETURNING id`).Scan(&id); err != nil || id != 1 {
			t.Fatalf("next id %d, %v; want 1", id, err)
		}
		exec(t, db, `ALTER TABLE a ALTER COLUMN v DROP NOT NULL`)
	})
	t.Run("changed schema", func(t *testing.T) {
		if got := NewDB(t); got == first {
			t.Fatal("a database whose schema a test changed was reused")
		}
	})
}

func exec(t *testing.T, db *sql.DB, stmts ...string) {
	t.Helper()
	for _, s := range stmts {
		if _, err := db.Exec(s); err != nil {
			t.Fatalf("%s: %v", s, err)
		}
	}
}

// On Spanner a database goes back to the pool emptied, its migrations'
// records kept, and the next test gets it.
func TestSpannerPool(t *testing.T) {
	if !Spanner() {
		t.Skip("Spanner only (" + SpannerEnv + ")")
	}
	var first string
	t.Run("write", func(t *testing.T) {
		first = NewDB(t)
		db := Open(t, first)
		defer db.Close()
		// A table of mmmigrate's (its prefix), not one of its real ones:
		// the database goes on to other tests, which migrate it.
		exec(t, db, `CREATE TABLE IF NOT EXISTS mmmigrate_pooltest (k bigint PRIMARY KEY)`,
			`CREATE TABLE IF NOT EXISTS a (id bigint PRIMARY KEY, v text NOT NULL)`,
			`CREATE TABLE IF NOT EXISTS b (id bigint PRIMARY KEY, a bigint NOT NULL REFERENCES a (id))`,
			`INSERT INTO mmmigrate_pooltest VALUES (1) ON CONFLICT (k) DO NOTHING`,
			`INSERT INTO a VALUES (1, 'x'), (2, 'y')`, `INSERT INTO b VALUES (1, 2)`)
	})
	t.Run("reuse", func(t *testing.T) {
		if got := NewDB(t); got != first {
			t.Fatalf("got %s, want the pool's %s", got, first)
		}
		db := Open(t, first)
		defer db.Close()
		var rows, kept int
		if err := db.QueryRow(`SELECT (SELECT count(*) FROM a) + (SELECT count(*) FROM b), (SELECT count(*) FROM mmmigrate_pooltest)`).Scan(&rows, &kept); err != nil || rows != 0 || kept == 0 {
			t.Fatalf("rows left %d, migration records %d, %v", rows, kept, err)
		}
	})
}
